import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "contracts", "lisa-api-v1.openapi.json");
const tsPath = path.join(root, "src", "web", "api-contract.generated.ts");
const swiftPath = path.join(
  root,
  "packaging",
  "ios-companion",
  "Sources",
  "APIContract.generated.swift",
);
const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const major = source["x-lisa-api-major"];
const header = source["x-lisa-version-header"];

if (!Number.isInteger(major) || major < 1) {
  throw new Error("x-lisa-api-major must be a positive integer");
}
if (typeof header !== "string" || !header) {
  throw new Error("x-lisa-version-header must be a non-empty string");
}
const declaredMajor = Number.parseInt(String(source.info?.version ?? "").split(".", 1)[0], 10);
if (declaredMajor !== major) {
  throw new Error("OpenAPI info.version major must match x-lisa-api-major");
}

// ── Error codes (contracts/lisa-error-codes.json) ──────────────────────────
const errorCodesPath = path.join(root, "contracts", "lisa-error-codes.json");
const errorCodesTsPath = path.join(root, "src", "web", "error-codes.generated.ts");
const errorTable = JSON.parse(fs.readFileSync(errorCodesPath, "utf8"));
const CODE_RE = /^[a-z][a-z0-9_]*$/;
// Swift words that cannot be a bare enum case name.
const SWIFT_RESERVED = new Set(
  (
    "associatedtype class deinit enum extension fileprivate func import init inout internal let " +
    "open operator private precedencegroup protocol public rethrows static struct subscript " +
    "typealias var break case catch continue default defer do else fallthrough for guard if in " +
    "repeat return throw switch where while as false is nil self super throws true try Any Self " +
    "Type unknown"
  ).split(" "),
);
const swiftCase = (code) => code.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

if (!Array.isArray(errorTable.codes) || errorTable.codes.length === 0) {
  throw new Error("lisa-error-codes.json: codes must be a non-empty array");
}
const seenCodes = new Set();
const seenCases = new Set();
for (const entry of errorTable.codes) {
  const { code, http, message } = entry;
  if (typeof code !== "string" || !CODE_RE.test(code)) {
    throw new Error(`lisa-error-codes.json: ${JSON.stringify(code)} is not a snake_case code`);
  }
  if (code === "unknown") throw new Error("lisa-error-codes.json: 'unknown' is the client's own");
  if (seenCodes.has(code)) throw new Error(`lisa-error-codes.json: duplicate code ${code}`);
  seenCodes.add(code);
  const name = swiftCase(code);
  if (SWIFT_RESERVED.has(name) || seenCases.has(name)) {
    throw new Error(`lisa-error-codes.json: ${code} has no usable Swift case name`);
  }
  seenCases.add(name);
  if (!Array.isArray(http) || http.some((s) => !Number.isInteger(s) || s < 400 || s > 599)) {
    throw new Error(`lisa-error-codes.json: ${code}.http must list 4xx/5xx statuses`);
  }
  if (http.length === 0 && entry.sse !== true && code !== errorTable.fallbackByStatus?.default) {
    throw new Error(`lisa-error-codes.json: ${code} is sent nowhere (no http status, not sse)`);
  }
  if (typeof message !== "string" || !message.trim() || !/[.!?]$/.test(message)) {
    throw new Error(`lisa-error-codes.json: ${code}.message must be a full sentence`);
  }
  if (typeof entry.when !== "string" || !entry.when.trim()) {
    throw new Error(`lisa-error-codes.json: ${code}.when must say when it is sent`);
  }
}
const fallback = errorTable.fallbackByStatus ?? {};
for (const [status, code] of Object.entries(fallback)) {
  if (status !== "default" && !/^[45]\d\d$/.test(status)) {
    throw new Error(`lisa-error-codes.json: fallbackByStatus key ${status} is not a 4xx/5xx`);
  }
  if (!seenCodes.has(code)) {
    throw new Error(`lisa-error-codes.json: fallback ${code} for ${status} is not in codes`);
  }
}
if (!fallback.default) throw new Error("lisa-error-codes.json: fallbackByStatus.default missing");

const generatedNote = "Generated by scripts/generate-api-contract.mjs; do not edit.";
const ts = `// ${generatedNote}
export const LISA_API_VERSION = ${JSON.stringify(String(major))};
export const LISA_API_VERSION_HEADER = ${JSON.stringify(header)};
`;
const record = (pairs) =>
  `{\n${pairs.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n")}\n}`;
const errorCodesTs = `// ${generatedNote}
// Source: contracts/lisa-error-codes.json (error codes v${errorTable.version}).

/** Default user-facing message for each error code. */
export const LISA_ERROR_MESSAGES: Readonly<Record<string, string>> = ${record(
  errorTable.codes.map((e) => [e.code, JSON.stringify(e.message)]),
)};

/** HTTP statuses each code is sent with; empty for chat-stream-only codes. */
export const LISA_ERROR_HTTP_STATUS: Readonly<Record<string, readonly number[]>> = ${record(
  errorTable.codes.map((e) => [e.code, JSON.stringify(e.http)]),
)};

/** Generic code for a non-2xx response whose route gives no specific one. */
export const LISA_ERROR_FALLBACK_BY_STATUS: Readonly<Record<string, string>> = ${record(
  Object.entries(fallback).map(([k, v]) => [k, JSON.stringify(v)]),
)};
`;
const swiftCases = errorTable.codes
  .map((e) => {
    const where = e.http.length
      ? `HTTP ${e.http.join(", ")}${e.sse ? " and chat stream" : ""}`
      : e.sse
        ? "Chat stream"
        : "Any other non-2xx status";
    const name = swiftCase(e.code);
    const raw = name === e.code ? "" : ` = ${JSON.stringify(e.code)}`;
    return `    /// ${where}. ${e.message}\n    case ${name}${raw}`;
  })
  .join("\n");
const swift = `// ${generatedNote}
import Foundation

enum LisaAPIContract {
    static let supportedMajorVersion = ${major}
    static let versionHeader = ${JSON.stringify(header)}
}

/// The \`error\` code of a LISA error body, or the \`code\` of a chat \`error\`
/// event (contracts/lisa-error-codes.json). Servers add codes over time: map
/// any code not listed here to \`.unknown\` and fall back to the HTTP status
/// and the server's \`message\`.
enum LisaErrorCode: String {
${swiftCases}
    /// A code this build doesn't know.
    case unknown
}
`;

const outputs = [
  [tsPath, ts],
  [errorCodesTsPath, errorCodesTs],
  [swiftPath, swift],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [file, expected] of outputs) {
  if (check) {
    const actual = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (actual !== expected) {
      console.error(`generated API contract is stale: ${path.relative(root, file)}`);
      stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, expected);
  }
}
if (stale) process.exitCode = 1;
