import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "contracts", "lisa-api-v1.openapi.json");
const tsPath = path.join(root, "src", "web", "api-contract.generated.ts");
const swiftPath = path.join(
  root,
  "packaging",
  "ios-companion",
  "Sources",
  "APIContract.generated.swift",
);
const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const major = source["x-lisa-api-major"];
const header = source["x-lisa-version-header"];

if (!Number.isInteger(major) || major < 1) {
  throw new Error("x-lisa-api-major must be a positive integer");
}
if (typeof header !== "string" || !header) {
  throw new Error("x-lisa-version-header must be a non-empty string");
}
const declaredMajor = Number.parseInt(String(source.info?.version ?? "").split(".", 1)[0], 10);
if (declaredMajor !== major) {
  throw new Error("OpenAPI info.version major must match x-lisa-api-major");
}

const generatedNote = "Generated by scripts/generate-api-contract.mjs; do not edit.";
const ts = `// ${generatedNote}
export const LISA_API_VERSION = ${JSON.stringify(String(major))};
export const LISA_API_VERSION_HEADER = ${JSON.stringify(header)};
`;
const swift = `// ${generatedNote}
import Foundation

enum LisaAPIContract {
    static let supportedMajorVersion = ${major}
    static let versionHeader = ${JSON.stringify(header)}
}
`;

const outputs = [
  [tsPath, ts],
  [swiftPath, swift],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [file, expected] of outputs) {
  if (check) {
    const actual = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (actual !== expected) {
      console.error(`generated API contract is stale: ${path.relative(root, file)}`);
      stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, expected);
  }
}
if (stale) process.exitCode = 1;
