/** Sync checked-in client mappings from the artwork manifest; no image generation here. */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/web/assets/visuals/soft-ink-v1");
const manifest = JSON.parse(await fs.readFile(path.join(dir, "manifest.json"), "utf8"));
const catalog = JSON.parse(
  await fs.readFile(path.join(root, "src/web/assets/lisa/index.json"), "utf8"),
);
const aliases = manifest.portraits.aliases;
if (
  catalog.moods.length !== Object.keys(aliases).length ||
  catalog.moods.some((m) => !Object.hasOwn(aliases, m.slug)) ||
  Object.values(aliases).some((i) => !Number.isInteger(i) || i < 0 || i >= 24)
) {
  throw new Error("Soft Ink must explicitly map every mood to an existing frame");
}
const swift = [
  "// Generated by scripts/sync-soft-ink.mjs. Edit the manifest, not this file.",
  "import Foundation",
  "",
  "enum LisaArtCatalog {",
  '    static let atlasPath = "' + manifest.portraits.nativeSrc + '"',
  "    static let columns = " + manifest.portraits.columns,
  "    static let rows = " + manifest.portraits.rows,
  "    static let moods: [String: Int] = [",
  ...Object.entries(aliases).map(([slug, index]) => '        "' + slug + '": ' + index + ","),
  "    ]",
  "}",
  "",
].join("\n");
const outputs = [
  [path.join(dir, "manifest.js"), "window.LISA_ART = " + JSON.stringify(manifest) + ";\n"],
  [path.join(root, "packaging/ios-companion/Sources/LisaArtCatalog.generated.swift"), swift],
];
for (const [file, content] of outputs) {
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(file, "utf8")) !== content) throw new Error("Out of date: " + file);
  } else await fs.writeFile(file, content);
}
console.log("Soft Ink: 114 mood mappings and Web/iOS manifest outputs verified.");
